package cli

import (
	"fmt"
	"sort"
	"strings"
)

var shells = []string{"bash", "zsh", "fish"}

func completionCommand() *Command {
	return &Command{
		Name:    "completion",
		Args:    "<shell>",
		Summary: "Print the shell completion script (bash, zsh, fish)",
		Complete: func(*Env) []string {
			return shells
		},
		Run: func(env *Env, args []string) int {
			if len(args) != 1 {
				return env.UsageError([]string{"completion"}, "completion takes exactly one shell: %s", strings.Join(shells, ", "))
			}
			script, ok := Completion(env.root, args[0], env)
			if !ok {
				return env.UsageError([]string{"completion"}, "unsupported shell: %s (want %s)", args[0], strings.Join(shells, ", "))
			}
			fmt.Fprint(env.Stdout, script)
			return ExitOK
		},
	}
}

// node is one completion position: the words typed so far (flags excluded)
// and what may follow them.
type node struct {
	path   string
	values []value
	flags  []Flag
}

type value struct{ word, summary string }

// walk flattens the registry into completion positions, sorted by path.
func walk(root *Command, env *Env) []node {
	var out []node
	var rec func(c *Command, path []string)
	rec = func(c *Command, path []string) {
		n := node{path: strings.Join(path, " "), flags: c.Flags}
		for _, s := range c.Sub {
			n.values = append(n.values, value{s.Name, s.Summary})
		}
		if c.Complete != nil {
			for _, v := range c.Complete(env) {
				n.values = append(n.values, value{word: v})
			}
		}
		out = append(out, n)
		for _, s := range c.Sub {
			rec(s, append(append([]string(nil), path...), s.Name))
		}
	}
	rec(root, nil)
	sort.Slice(out, func(i, j int) bool { return out[i].path < out[j].path })
	return out
}

// Completion returns the completion script for shell, generated from root.
func Completion(root *Command, shell string, env *Env) (string, bool) {
	nodes := walk(root, env)
	switch shell {
	case "bash":
		return bashCompletion(nodes), true
	case "zsh":
		return zshCompletion(nodes), true
	case "fish":
		return fishCompletion(nodes), true
	}
	return "", false
}

func flagNames(flags []Flag) []string {
	out := make([]string, 0, len(flags))
	for _, f := range flags {
		out = append(out, f.Name)
	}
	return out
}

func words(vs []value) []string {
	out := make([]string, 0, len(vs))
	for _, v := range vs {
		out = append(out, v.word)
	}
	return out
}

func bashCompletion(nodes []node) string {
	var b strings.Builder
	b.WriteString("# bash completion for kombinat; generated by `kombinat completion bash`, do not edit.\n")
	b.WriteString("_kombinat() {\n")
	b.WriteString("  local cur=${COMP_WORDS[COMP_CWORD]} p=\"\" w i words=\"\"\n")
	b.WriteString("  for ((i = 1; i < COMP_CWORD; i++)); do\n")
	b.WriteString("    w=${COMP_WORDS[i]}\n")
	b.WriteString("    [[ $w == -* ]] && continue\n")
	b.WriteString("    p+=\"${p:+ }$w\"\n")
	b.WriteString("  done\n")
	b.WriteString("  if [[ $cur == -* ]]; then\n")
	b.WriteString("    case $p in\n")
	for _, n := range nodes {
		if len(n.flags) > 0 {
			fmt.Fprintf(&b, "      %q) words=%q ;;\n", n.path, strings.Join(flagNames(n.flags), " "))
		}
	}
	b.WriteString("    esac\n")
	fmt.Fprintf(&b, "    words+=\" %s\"\n", strings.Join(flagNames(globalFlags), " "))
	b.WriteString("  else\n")
	b.WriteString("    case $p in\n")
	for _, n := range nodes {
		if len(n.values) > 0 {
			fmt.Fprintf(&b, "      %q) words=%q ;;\n", n.path, strings.Join(words(n.values), " "))
		}
	}
	b.WriteString("    esac\n")
	b.WriteString("  fi\n")
	b.WriteString("  mapfile -t COMPREPLY < <(compgen -W \"$words\" -- \"$cur\")\n")
	b.WriteString("}\n")
	b.WriteString("complete -F _kombinat kombinat\n")
	return b.String()
}

// zshQuote single-quotes s for zsh.
func zshQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func zshCompletion(nodes []node) string {
	var b strings.Builder
	b.WriteString("#compdef kombinat\n")
	b.WriteString("# zsh completion for kombinat; generated by `kombinat completion zsh`, do not edit.\n")
	b.WriteString("_kombinat() {\n")
	b.WriteString("  local -a typed vals\n")
	b.WriteString("  local w p\n")
	b.WriteString("  for w in \"${(@)words[2,CURRENT-1]}\"; do\n")
	b.WriteString("    [[ $w == -* ]] || typed+=(\"$w\")\n")
	b.WriteString("  done\n")
	b.WriteString("  p=\"${(j: :)typed}\"\n")
	b.WriteString("  if [[ $PREFIX == -* ]]; then\n")
	b.WriteString("    case $p in\n")
	for _, n := range nodes {
		if len(n.flags) > 0 {
			entries := make([]string, 0, len(n.flags))
			for _, f := range n.flags {
				entries = append(entries, zshQuote(f.Name+":"+f.Summary))
			}
			fmt.Fprintf(&b, "      %s) vals=(%s) ;;\n", zshQuote(n.path), strings.Join(entries, " "))
		}
	}
	b.WriteString("    esac\n")
	for _, f := range globalFlags {
		fmt.Fprintf(&b, "    vals+=(%s)\n", zshQuote(f.Name+":"+f.Summary))
	}
	b.WriteString("    _describe -t flags 'kombinat flag' vals\n")
	b.WriteString("    return\n")
	b.WriteString("  fi\n")
	b.WriteString("  case $p in\n")
	for _, n := range nodes {
		if len(n.values) > 0 {
			entries := make([]string, 0, len(n.values))
			for _, v := range n.values {
				e := strings.ReplaceAll(v.word, ":", `\:`)
				if v.summary != "" {
					e += ":" + v.summary
				}
				entries = append(entries, zshQuote(e))
			}
			fmt.Fprintf(&b, "    %s) vals=(%s) ;;\n", zshQuote(n.path), strings.Join(entries, " "))
		}
	}
	b.WriteString("  esac\n")
	b.WriteString("  (( ${#vals} )) && _describe -t values 'kombinat' vals\n")
	b.WriteString("}\n")
	b.WriteString("_kombinat \"$@\"\n")
	return b.String()
}

// fishQuote single-quotes s for fish.
func fishQuote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	return "'" + strings.ReplaceAll(s, "'", `\'`) + "'"
}

func fishCompletion(nodes []node) string {
	var b strings.Builder
	b.WriteString("# fish completion for kombinat; generated by `kombinat completion fish`, do not edit.\n")
	b.WriteString("function __kombinat_at --argument-names want\n")
	b.WriteString("    set -l toks (commandline -opc)\n")
	b.WriteString("    set -e toks[1]\n")
	b.WriteString("    set -l typed\n")
	b.WriteString("    for t in $toks\n")
	b.WriteString("        string match -q -- '-*' $t; or set -a typed $t\n")
	b.WriteString("    end\n")
	b.WriteString("    set -l got (string join ' ' -- $typed)\n")
	b.WriteString("    test \"$got\" = \"$want\"\n")
	b.WriteString("end\n")
	b.WriteString("complete -c kombinat -f\n")
	for _, f := range globalFlags {
		fmt.Fprintf(&b, "complete -c kombinat -l %s -d %s\n", strings.TrimPrefix(f.Name, "--"), fishQuote(f.Summary))
	}
	for _, n := range nodes {
		cond := fishQuote("__kombinat_at " + fishQuote(n.path))
		for _, v := range n.values {
			line := fmt.Sprintf("complete -c kombinat -n %s -a %s", cond, fishQuote(v.word))
			if v.summary != "" {
				line += " -d " + fishQuote(v.summary)
			}
			b.WriteString(line + "\n")
		}
		for _, f := range n.flags {
			line := fmt.Sprintf("complete -c kombinat -n %s -l %s", cond, strings.TrimPrefix(f.Name, "--"))
			if f.Arg != "" {
				line += " -r"
			}
			b.WriteString(line + " -d " + fishQuote(f.Summary) + "\n")
		}
	}
	return b.String()
}
